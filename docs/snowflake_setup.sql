-- Configuración única de Snowflake para el PSet 2. Ejecutar en Snowsight con ACCOUNTADMIN.
-- Principio de mínimo privilegio: un usuario de SERVICIO (sin contraseña, solo par de llaves)
-- con un rol que solo puede trabajar dentro de la base PSET2.

USE ROLE ACCOUNTADMIN;

-- Tope de gasto: el trial trae créditos limitados; se suspende el warehouse al llegar al 100 %.
CREATE RESOURCE MONITOR IF NOT EXISTS PSET2_MONITOR WITH CREDIT_QUOTA = 20
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;

CREATE WAREHOUSE IF NOT EXISTS PSET2_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
ALTER WAREHOUSE PSET2_WH SET RESOURCE_MONITOR = PSET2_MONITOR;

CREATE DATABASE IF NOT EXISTS PSET2;
CREATE SCHEMA IF NOT EXISTS PSET2.RAW;      -- datos tal como llegan (append-only)
CREATE SCHEMA IF NOT EXISTS PSET2.BRONZE;   -- dbt: tipado 1:1 + seeds
CREATE SCHEMA IF NOT EXISTS PSET2.SILVER;   -- dbt: limpieza y reglas de negocio
CREATE SCHEMA IF NOT EXISTS PSET2.GOLD;     -- dbt: star schema
CREATE SCHEMA IF NOT EXISTS PSET2.OBT;      -- Spark: One Big Table + auditoría

CREATE ROLE IF NOT EXISTS PSET2_ROLE;
GRANT USAGE ON WAREHOUSE PSET2_WH TO ROLE PSET2_ROLE;
GRANT USAGE ON DATABASE PSET2 TO ROLE PSET2_ROLE;
GRANT ALL PRIVILEGES ON ALL SCHEMAS IN DATABASE PSET2 TO ROLE PSET2_ROLE;
GRANT ROLE PSET2_ROLE TO ROLE SYSADMIN;     -- para inspeccionar desde Snowsight

